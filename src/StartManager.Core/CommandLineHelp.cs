namespace StartManager.Core;

public static class CommandLineHelp
{
    public const string Text = """
        БазоНавигатор — список и запуск информационных баз 1С 8.x

        Использование:
          BaseNavigator [--settings <файл>] [--list <список.v8i>]
          BaseNavigator [параметры] --launch <GUID> [--mode enterprise|designer] [--no-gui]
          BaseNavigator --help | -h | --version
          BaseNavigator --check-update | --update | --rollback [<версия>]
          BaseNavigator --install-desktop | --uninstall-desktop

        Параметры:
          --help, -h          Справка без открытия окна и чтения профиля.
          --version           Номер сборки без открытия окна и чтения профиля.
          --settings <файл>   Файл настроек (относительный путь разрешён).
          --portable          Settings рядом с программой, только в этом запуске.
          --normal            Пользовательский каталог BaseNavigator, только в этом запуске.
          --single-instance   Запрет второго окна с тем же профилем; ярлыки баз не блокируются.
          --list <путь>       Полный путь к .v8i; пустая строка "" — локальный список.
                              В GUI выбор временный, сохранённый список не меняется автоматически.
          --launch <GUID>     Запуск базы по ID; без --list используется список из профиля.
          --mode <режим>      enterprise (по умолчанию) или designer.
          --no-gui            Без окон БазоНавигатора, ошибки в stderr. Сама 1С открывается обычно.
          --log-level <уровень> off | error | warning | info | debug, только в этом запуске.
          --log-dir <путь>    Полный путь к каталогу диагностического журнала.
          --check-update      Сравнить версию с последним выпуском на GitHub (по HTTPS; запасной путь — gh).
          --update            Скачать и установить последний выпуск того же варианта; прежняя версия — в архив .versions.
          --rollback [<версия>] Восстановить версию из архива .versions: указанную или последнюю сохранённую
                              (повторный вызов без номера возвращает обратно).
          --install-desktop   Только Linux: добавить БазоНавигатор в меню приложений (повторный вызов
                              обновляет путь к программе).
          --uninstall-desktop Только Linux: убрать БазоНавигатор из меню приложений.

        Приоритет: явный ключ > профиль > значение по умолчанию.
        --settings приоритетнее --portable/--normal; эти два режима вместе недопустимы.
        Справка, версия, команды обновления и ярлыка меню приложений используются отдельно;
        с ними допустим только --no-gui.
        Обновление меняет только файлы программы; настройки и метка портативного режима не затрагиваются.
        --no-gui без --launch (или справки, версии, команд обновления и ярлыка меню приложений) — ошибка.
        Старые ярлыки с --settings, --list, --launch, --mode поддерживаются.
        --single-instance действует только на окно списка; при --launch не применяется.
        История запусков ведётся отдельно от диагностического журнала, в том числе при --log-level off.

        Коды завершения:
          0  Успех; при --launch создан процесс 1С (успешный вход в базу не проверяется).
          1  Непредвиденная ошибка приложения; ярлык меню приложений не создан или не удалён.
          2  Ошибка аргументов; ярлык меню приложений запрошен не в Linux.
          3  Не удалось прочитать профиль/список или найти базу.
          4  Не удалось запустить клиент 1С.
          5  Клиент уже запущен, но история не сохранена. Не повторяйте запуск автоматически.
          6  Окно с этим профилем уже открыто или недоступна обязательная блокировка.
          7  Обновление, откат или проверка обновления не выполнены.
          8  --check-update: доступна более новая версия.

        Примеры:
          BaseNavigator.exe --portable --single-instance
          BaseNavigator.exe --list "D:\Списки баз\общий.v8i"
          ./BaseNavigator --settings "/home/user/profile.json" --list ""
          ./BaseNavigator --launch 11111111-1111-1111-1111-111111111111 --mode designer --no-gui

        В PowerShell для ожидания Windows GUI-exe и получения вывода используйте конвейер:
          & .\BaseNavigator.exe --help | Out-Host
          & .\BaseNavigator.exe --no-gui --launch <GUID> | Out-Host
          $LASTEXITCODE
        Для сохранения вывода: $version = & .\BaseNavigator.exe --version | Out-String
        В cmd.exe дождитесь завершения через start /wait:
          start /wait "" BaseNavigator.exe --help
          echo %ERRORLEVEL%
        """;
}
